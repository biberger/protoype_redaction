class Doc:
    """A document as (text, label) segments; rendered to tagged markdown."""

    def __init__(self):
        self.segs = []

    def t(self, text):
        self.segs.append((text, None))

    def e(self, label, text):
        self.segs.append((text, label))

    def nl(self):
        self.t("\n")

    def render(self):
        out = []
        for text, lab in self.segs:
            if lab and text.strip():
                out.append(f"[[{lab}|{text}]]")
            else:
                out.append(text)
        return "".join(out)


# --- small generators -------------------------------------------------------------------------------------------------

def _tz(rng, year=None):
    year = year or rng.randint(1950, 2025)
    return f"{rng.randint(1, 12000 if year > 2011 else 7000)}/{year}"


def _date(rng, lo=1950, hi=2025):
    return f"{rng.randint(lo, hi)}-{rng.randint(1, 12):02d}-{rng.randint(1, 28):02d}"


def _gst(rng):
    n = rng.randint(1, 1600)
    return str(n) if rng.random() < 0.45 else f"{n}/{rng.randint(1, 30 if rng.random() < 0.9 else 130)}"


def _abbr_street(street, rng):
    if rng.random() < 0.35:
        street = re.sub(r"straße$", "str.", street)
        street = re.sub(r"gasse$", "g.", street)
    return street


class Cast:
    def __init__(self, gaz, rng):
        self.gaz, self.rng = gaz, rng

    def town(self):
        name, pc = self.gaz.town("AT")
        return name, pc

    def kg(self):
        name, _ = self.town()
        return f"{self.rng.randint(1001, 99999):05d}", name

    def person(self):
        g = self.rng.choice("MF")
        first = transliterate(self.gaz.first_name("AT" if self.rng.random() < 0.75 else
                                                  self.rng.choice(["DE", "CZ", "HU", "HR", "IT", "TR", "RS"]), g))
        if self.rng.random() < 0.15:
            first += " " + transliterate(self.gaz.first_name("AT", g))
        last = transliterate(self.gaz.last_name("AT" if self.rng.random() < 0.8 else self.rng.choice(["DE", "CZ", "HU"])))
        if self.rng.random() < 0.05:
            last += "-" + transliterate(self.gaz.last_name("AT"))
        return first, last

    def address(self, rural=None):
        rng = self.rng
        town, pc = self.town()
        if rural is None:
            rural = rng.random() < 0.4
        if rural:
            village = town if rng.random() < 0.5 else self.town()[0]
            n = rng.randint(1, 80)
            form = rng.choice(["{v} {n}, {t} {pc}", "{v} {n} {pc}", "{t} {v} {n} {pc}", "{v} {n}, {v} {pc}"])
            return form.format(v=village, n=n, t=town, pc=pc)
        street = _abbr_street(rng.choice(self.gaz.streets["AT"]), rng)
        n = f"{rng.randint(1, 120)}" + (f"/{rng.randint(1, 30)}" if rng.random() < 0.4 else "") + \
            (f"/{rng.randint(1, 30)}" if rng.random() < 0.15 else "")
        if town in ("Wien",) or rng.random() < 0.2:
            return f"{street} {n}, Wien {rng.choice([1010, 1030, 1040, 1050, 1070, 1080, 1090, 1100, 1120, 1140, 1160, 1190, 1210, 1220])}"
        return f"{street} {n}, {town} {pc}"

    def bank(self):
        tpl, local = self.rng.choice(BANKS)
        name = tpl.format(town=self.town()[0]) if local else tpl
        fn = F.fn(self.rng) if self.rng.random() < 0.6 else None
        return name, fn


def person_name(rng, first, last, order=None, degree=None):
    """A person as written in an extract: given name first (B sheet) or surname first (older C entries)."""
    order = order or rng.choices(["first", "last"], [0.75, 0.25])[0]
    if degree and rng.random() < 0.6:  # "Jiri Dipl.Ing.(FH) Schneider", "Eleonore Dr. Schneider"
        return f"{first} {degree} {last}"
    if degree:
        return f"{degree} {first} {last}"
    return f"{first} {last}" if order == "first" else f"{last} {first}"


def maybe_split(rng, text, p=0.12):
    """Break a value across lines at a space or at any character (text-layer splits)."""
    if len(text) < 6 or rng.random() >= p:
        return text
    spaces = [m.start() for m in re.finditer(" ", text)]
    if spaces and rng.random() < 0.7:
        i = rng.choice(spaces)
        return text[:i] + "\n" + text[i + 1:]
    i = rng.randint(2, len(text) - 2)
    return text[:i] + "\n" + text[i:]



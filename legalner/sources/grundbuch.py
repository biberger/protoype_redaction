# --- OCR mode ---------------------------------------------------------------------------------------------------------

OCR_MAP = [("0", "O"), ("O", "0"), ("1", "l"), ("l", "1"), ("1", "I"), ("5", "S"), ("8", "B"), ("/", "l"), ("/", "1"),
           ("Z", "2"), ("G", "6"), ("rn", "m"), ("ü", "u"), ("ö", "o"), ("ä", "a"), ("ß", "B"), ("e", "c"), ("*", "x")]


def ocr(doc, rng, p=0.015):
    """Scanned extracts: character confusions and stray spaces, applied to the text of every segment."""
    segs = []
    for text, lab in doc.segs:
        out, i = [], 0
        while i < len(text):
            if text[i] not in "\n" and rng.random() < p:
                for a, b in rng.sample(OCR_MAP, len(OCR_MAP)):
                    if text.startswith(a, i):
                        out.append(b)
                        i += len(a)
                        break
                else:
                    out.append(text[i])
                    i += 1
                if rng.random() < 0.2 and i < len(text) and text[i] != "\n":
                    out.append(" ")
                continue
            out.append(text[i])
            i += 1
        new = "".join(out)
        if lab:
            new = new.strip() or text
        segs.append((new, lab))
    doc.segs = segs
    return doc


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--docs", type=int, default=200)
    ap.add_argument("--ocr-frac", type=float, default=0.25, help="share written as scanned (OCR noise)")
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("-o", "--out", required=True)
    args = ap.parse_args(argv)
    rng = random.Random(args.seed)
    gaz = Gazetteer(rng=rng)
    out = pathlib.Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    for i in range(args.docs):
        doc = extract(gaz, rng, i)
        scanned = rng.random() < args.ocr_frac
        if scanned:
            doc = ocr(doc, rng)
        body = re.sub(r"\n{3,}", "\n\n", doc.render())
        (out / f"AT_gb_{i + 1:04d}_grundbuchsauszug.md").write_text(
            f"---\ndoc_type: grundbuchsauszug{'_scan' if scanned else ''}\njurisdiction: AT\nlang: de\n---\n{body}",
            encoding="utf-8")
    print(f"{args.docs} extracts -> {out}")


if __name__ == "__main__":
    main()

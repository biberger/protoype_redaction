def land_ref(rng, kg_code, kg_name, ez, gst=None, court=None):
    """An informal land register reference as a Doc (tagged segments), in a random order and spelling."""
    d = Doc()
    ez_kw = rng.choice(["EZ ", "EZ ", "EZ ", "EZ", "E.Z. ", "EZ. ", "EZ: ", "Einlagezahl "])
    kg_kw = rng.choice(["KG ", "KG ", "KG ", "K.G. ", "KG: ", "GB ", "Katastralgemeinde ", "Grundbuch "])
    kg_val = rng.choice([f"{kg_code} {kg_name}", f"{kg_code} {kg_name}", kg_name, kg_code])
    sep = rng.choice([" ", " ", ", ", "/", " / ", " der ", " des Grundbuchs "])
    style = rng.random()

    def ez_part():
        if ez_kw.startswith("Einlagezahl"):
            d.t(ez_kw)
            d.e("land_register_id", ez)
        else:
            d.e("land_register_id", f"{ez_kw}{ez}")

    def kg_part():
        if kg_kw.startswith(("Katastralgemeinde", "Grundbuch")):
            d.t(kg_kw)
            d.e("land_register_id", kg_val)
        else:
            d.e("land_register_id", f"{kg_kw}{kg_val}")

    if style < 0.08:  # bare compound "123/Penzing"
        d.e("land_register_id", f"{ez}/{kg_name}")
    elif style < 0.55:
        ez_part()
        d.t(sep if sep not in (" der ", " des Grundbuchs ") else rng.choice([" ", ", "]))
        kg_part()
    else:
        kg_part()
        d.t(rng.choice([" ", ", ", "/", " / "]))
        ez_part()
    if court and rng.random() < 0.3:
        d.t(" (")
        d.e("court", f"BG {court}")
        d.t(")")
    if gst and rng.random() < 0.6:
        d.t(rng.choice([", ", " ", "; "]))
        kw = rng.choice(["Gst ", "Gst-Nr. ", "Gst.Nr. ", "GSt-Nr. ", "Parz. ", "Grundstück Nr. ", "Grundstück "])
        if kw.startswith("Grundstück"):
            d.t(kw)
            d.e("land_register_id", gst)
        else:
            d.e("land_register_id", f"{kw}{gst}")
    return d



    p = {"name": transliterate(f"{gaz.first_name(country, g)} {surname(gaz, country, g)}"), "gender": g}
    if rng.random() < 0.15:
        p["degree"] = rng.choice(["Dr.", "Mag.", "DI", "Ing.", "Mag. Dr.", "MMag.", "Dipl.-Ing."])
        p["degree_position"] = rng.choice(["before", "before", "between"])
